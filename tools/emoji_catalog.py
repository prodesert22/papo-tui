"""Generate the offline Unicode 17 / CLDR 48 catalogue from vendored inputs."""
from pathlib import Path
import argparse
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]

def generate():
    names = {}
    for lang in ('en', 'pt'):
        entries = {}
        for suffix in ('', '-derived'):
            for annotation in ET.parse(ROOT / 'data/emoji' / f'{lang}{suffix}.xml').iter('annotation'):
                item = entries.setdefault(annotation.attrib['cp'].replace('\ufe0f', ''), {})
                item['name' if annotation.attrib.get('type') == 'tts' else 'keywords'] = annotation.text or ''
        names[lang] = entries
    records, aliases = [], []
    for line in (ROOT / 'data/emoji/emoji-test.txt').read_text().splitlines():
        if ';' not in line or line.startswith('#'): continue
        codes, rest = line.split(';', 1)
        status, description = rest.split('#', 1)
        points = tuple(int(code, 16) for code in codes.split())
        text = ''.join(map(chr, points))
        # Text presentation symbols require VS16, rather than changing ordinary
        # punctuation/digits into images. ZWJ sequences and flags remain atomic.
        if status.strip() != 'fully-qualified':
            if len(points) > 1: aliases.append((points, text.replace('\ufe0f', '')))
            continue
        key = text.replace('\ufe0f', '')
        en = names['en'].get(key, {})
        pt = names['pt'].get(key, {})
        fallback = description.strip().split(' ', 2)[-1]
        records.append((points, text, pt.get('name', en.get('name', fallback)),
                        en.get('name', fallback), ' | '.join((pt.get('keywords', ''), en.get('keywords', '')))))
    display_order = [r[0] for r in records]
    records.sort()
    canonical = {r[1].replace('\ufe0f', ''): i for i, r in enumerate(records)}
    q = lambda s: json.dumps(s, ensure_ascii=False)
    out = ['/* Generated by tools/emoji_catalog.py; Unicode-3.0, see data/emoji/LICENSE. */']
    for i, (points, *_rest) in enumerate(records):
        out.append(f'static const uint32_t emoji_points_{i}[] = {{{",".join(hex(p) for p in points)}}};')
    out.append('static const unicode_emoji catalogue[] = {')
    for i, (points, text, name, english, words) in enumerate(records):
        out.append(f'    {{{q(text)}, {q(name)}, {q(english)}, {q(words)}, emoji_points_{i}, {len(points)}}},')
    out.append('};')
    out.append('typedef struct { uint32_t points[16]; size_t length, index; } emoji_alias;')
    out.append('static const emoji_alias emoji_aliases[] = {')
    for points, key in sorted(set(aliases)):
        if key in canonical and len(points) <= 16:
            out.append(f'    {{{{{",".join(hex(p) for p in points)}}}, {len(points)}, {canonical[key]}}},')
    out.append('};')
    sorted_indices = {r[0]: i for i, r in enumerate(records)}
    out.append('static const size_t emoji_order[] = {' + ','.join(str(sorted_indices[points]) for points in display_order) + '};\n')
    return '\n'.join(out)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'src/model/emoji_data.inc'
    data = generate()
    if args.check:
        if target.read_text() != data: raise SystemExit('Emoji catalogue is out of date')
    else: target.write_text(data)
