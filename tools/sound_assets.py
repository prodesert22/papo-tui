"""Generate the notification and call sounds embedded in the client.

The sounds are synthesized here from short tone recipes, so they carry the
project's own license. Only integer arithmetic is used, which keeps the output
identical on every platform and lets --check compare it byte for byte.
"""

from pathlib import Path
import argparse
import io
import wave

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "src/ui/media/sound_data.inc"
RATE = 16000
PERIOD = 1 << 16  # Phase units per cycle.
HALF = PERIOD // 2
PEAK = 32767

# name -> notes of (frequency Hz, start ms, duration ms, amplitude in 1/1000).
SOUNDS = {
    "message": [(880, 0, 110, 300), (1319, 70, 150, 260)],
    "mention": [(784, 0, 100, 300), (988, 70, 100, 300), (1319, 140, 190, 280)],
    "call_join": [(523, 0, 120, 280), (784, 90, 200, 280)],
    "call_leave": [(784, 0, 120, 280), (523, 90, 200, 280)],
    "peer_join": [(659, 0, 80, 220), (880, 60, 120, 220)],
    "peer_leave": [(880, 0, 80, 220), (659, 60, 120, 220)],
}


def sine(phase):
    """Bhaskara I's approximation, scaled to PEAK, for phase in [0, PERIOD)."""
    h = phase % HALF
    value = 16 * h * (HALF - h) * PEAK // (5 * HALF * HALF - 4 * h * (HALF - h))
    return value if phase < HALF else -value


def render(notes):
    length = max(start + duration for _, start, duration, _ in notes) * RATE // 1000
    samples = [0] * length
    for frequency, start, duration, amplitude in notes:
        first, count = start * RATE // 1000, duration * RATE // 1000
        attack = RATE // 200  # 5 ms, so the tone starts without a click.
        for i in range(count):
            # Quadratic decay to silence; linear attack.
            envelope = (count - i) * (count - i) * 1000 // (count * count)
            if i < attack:
                envelope = envelope * i // attack
            phase = i * frequency * PERIOD // RATE % PERIOD
            samples[first + i] += sine(phase) * amplitude * envelope // 1000000
    return [max(-PEAK, min(PEAK, s)) for s in samples]


def wav(samples):
    buffer = io.BytesIO()
    with wave.open(buffer, "wb") as out:
        out.setnchannels(1)
        out.setsampwidth(2)
        out.setframerate(RATE)
        out.writeframes(b"".join(s.to_bytes(2, "little", signed=True) for s in samples))
    return buffer.getvalue()


def generate():
    out = [
        "/* Generated by tools/sound_assets.py; synthesized tones under the project license. */",
    ]
    for name, notes in SOUNDS.items():
        data = wav(render(notes))
        out.append(f"static const unsigned char sound_{name}_wav[{len(data)}] = {{")
        for at in range(0, len(data), 16):
            out.append("    " + ",".join(f"0x{b:02x}" for b in data[at : at + 16]) + ",")
        out.append("};")
    out.append("static const struct {")
    out.append("    const char *name;")
    out.append("    const unsigned char *data;")
    out.append("    size_t size;")
    out.append("} sound_assets[] = {")
    for name in SOUNDS:
        out.append(f'    {{"{name}", sound_{name}_wav, sizeof(sound_{name}_wav)}},')
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != data:
            raise SystemExit("Sound assets are out of date; run python -m tools.sound_assets")
    else:
        TARGET.write_text(data)
